package main

import (
  "text/template"
  "bytes"
  //"log"
  "os"
  "strings"
)

type LyBuffer struct {
  includes []string 
  tags string
  name string
  file *os.File
  calls []string 
}


func InitBuffer(inst_name string, tags string, file *os.File) LyBuffer {
  var lb LyBuffer
  lb.tags = tags
  lb.name = inst_name
  lb.file = file

  return lb
}

var (
  incl_template = template.Must(template.New("incl_templ").Parse(`\include "{{.}}"
`))
  toc_template = template.Must(template.New("toc_templ").Parse(`\tocItem {{.TocIden}} \markup { "{{.TocName}}" }`))
  header_template = template.Must(template.New("header_templ").Parse(`\header {
      {{.HeaderVar}}
    }`))
  score_template = template.Must(template.New("score_templ").Parse(`\score {
      \keepWithTag #'({{.Tags}}) {{.ScoreVar}}

      \layout {}
    }`))
  bookpart_template = template.Must(template.New("bp_templ").Parse(`\bookpart {
    {{.TocString}}

    {{.HeaderString}}
    {{.ScoreString}}
  }

  `))
  tacet_template = template.Must(template.New("tacet_templ").Parse(`\bookpart {
    \tocItem {{.TocIden}} \markup { "{{.TocName}}" }

    \header {
      {{.HeaderVar}}
    }
    \markup {
      \vspace #14

      \fill-line {
        "Tacet"
      }
    }
  }

  `))
)

func (lb *LyBuffer) AddPiece(piece_data PieceData) {
  // add includes
  var inclbuffer bytes.Buffer 
  incl_template.Execute(&inclbuffer, piece_data.IncludeString)
  lb.includes = append(lb.includes, inclbuffer.String())

  // add to calls
  var tocbuffer, headerbuffer, scorebuffer, bookpartbuffer bytes.Buffer 

  toc_template.Execute(&tocbuffer, piece_data)
  header_template.Execute(&headerbuffer, piece_data)
  score_template.Execute(&scorebuffer, struct {Tags string; ScoreVar string} {Tags: lb.tags, ScoreVar: piece_data.ScoreVar})

  bookpart_template.Execute(&bookpartbuffer, struct {
    TocString string
    HeaderString string 
    ScoreString string
  } {
    TocString: tocbuffer.String(),
    HeaderString: headerbuffer.String(),
    ScoreString: scorebuffer.String(),
  })

  lb.calls = append(lb.calls, bookpartbuffer.String())
}

func (lb *LyBuffer) AddTacet(piece_data PieceData) {
  // add includes
  var inclbuffer bytes.Buffer 
  incl_template.Execute(&inclbuffer, piece_data.IncludeString)
  lb.includes = append(lb.includes, inclbuffer.String())

  // add to calls 
  var tacetbuffer bytes.Buffer 
  tacet_template.Execute(&tacetbuffer, piece_data)
  lb.calls = append(lb.calls, tacetbuffer.String())
}

